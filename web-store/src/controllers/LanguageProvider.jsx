function readLanguage() {
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'vi'; }
  catch { return 'vi'; }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(readLanguage);
  const toggleLanguage = useCallback(() => setLanguage((current) => current === 'vi' ? 'en' : 'vi'), []);
  const t = useCallback((vietnamese) => {
    if (language !== 'en') return vietnamese;
    const exact = english[vietnamese] || additionalEnglish[vietnamese];
    if (exact) return exact;
    const customDesignPrefix = 'Thiết kế riêng · ';
    if (vietnamese.startsWith(customDesignPrefix)) return 'Custom design · ' + vietnamese.slice(customDesignPrefix.length);
    return vietnamese;
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === 'vi' ? 'Wavo | Biển đẹp, tâm sáng' : 'Wavo | Beautiful sea, bright spirit';
    try { localStorage.setItem(STORAGE_KEY, language); } catch { /* Storage may be unavailable in private mode. */ }
  }, [language]);

  const value = useMemo(() => ({ language, toggleLanguage, t }), [language, toggleLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage phải được gọi trong LanguageProvider');
  return value;
}

export function getLocalizedProductField(product, field, language, t) {
  if (!product) return '';
  if (language === 'en') {
    const enValue = product[field + 'En'];
    if (enValue && String(enValue).trim()) return enValue;
  }
  const baseValue = product[field] || '';
  return typeof t === 'function' ? t(baseValue) : baseValue;
}
